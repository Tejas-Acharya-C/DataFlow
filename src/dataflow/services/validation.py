import uuid
from typing import Any, Dict, List, Optional, Tuple

import pandas as pd
from sqlalchemy import func, select
from sqlalchemy.orm import Session

from dataflow.models.contract import DataContract, ValidationRejection, ValidationRun
from dataflow.models.dataset import DatasetVersion
from dataflow.schemas.contract import CheckResult
from dataflow.services.audit import complete_job, create_job, log_audit
from dataflow.services.retry import classify_exception
from dataflow.storage.local import LocalStorageManager


class ValidationService:
    """Validates dataset versions against declarative data contracts."""

    def __init__(self, storage: Optional[LocalStorageManager] = None):
        self.storage = storage or LocalStorageManager()

    def validate_version(
        self,
        db: Session,
        version: DatasetVersion,
        contract: DataContract,
    ) -> ValidationRun:
        """Execute contract checks on dataset version and record run."""
        job = create_job(
            db,
            job_type="contract_validation",
            dataset_id=version.dataset_id,
            version_id=version.id,
            metadata={"contract_id": contract.id, "contract_name": contract.name},
        )

        try:
            df = self.storage.load_dataframe(version.storage_path)
            rules = contract.rules_json or {}
            check_results: List[CheckResult] = []
            row_errors: Dict[int, List[Dict[str, Any]]] = {}

            actual_cols = list(df.columns)
            row_count = len(df)

            # 1. Dataset-level row constraints
            min_rows = rules.get("min_rows")
            if min_rows is not None:
                if row_count < min_rows:
                    check_results.append(
                        CheckResult(
                            name="min_rows_check",
                            category="dataset_constraint",
                            status="failed",
                            severity="error",
                            message=f"Dataset has {row_count} rows, below required minimum of {min_rows}",
                            failed_count=min_rows - row_count,
                            recommendation=f"Ensure upstream pipeline provides at least {min_rows} records.",
                        )
                    )
                else:
                    check_results.append(
                        CheckResult(
                            name="min_rows_check",
                            category="dataset_constraint",
                            status="passed",
                            severity="error",
                            message=f"Dataset satisfies minimum row requirement ({row_count} >= {min_rows})",
                        )
                    )

            max_rows = rules.get("max_rows")
            if max_rows is not None:
                if row_count > max_rows:
                    check_results.append(
                        CheckResult(
                            name="max_rows_check",
                            category="dataset_constraint",
                            status="failed",
                            severity="error",
                            message=f"Dataset has {row_count} rows, exceeding maximum limit of {max_rows}",
                            failed_count=row_count - max_rows,
                            recommendation=f"Filter or partition data before ingestion to stay under {max_rows} rows.",
                        )
                    )
                else:
                    check_results.append(
                        CheckResult(
                            name="max_rows_check",
                            category="dataset_constraint",
                            status="passed",
                            severity="error",
                            message=f"Dataset satisfies maximum row requirement ({row_count} <= {max_rows})",
                        )
                    )

            # 2. Required columns check
            required_cols = rules.get("required_columns", [])
            for col in required_cols:
                if col not in actual_cols:
                    check_results.append(
                        CheckResult(
                            name=f"required_column:{col}",
                            category="schema_requirement",
                            status="failed",
                            severity="error",
                            message=f"Required column '{col}' is missing from the dataset.",
                            affected_column=col,
                            failed_count=1,
                            recommendation=f"Verify CSV headers and ensure '{col}' is generated by source.",
                        )
                    )
                else:
                    check_results.append(
                        CheckResult(
                            name=f"required_column:{col}",
                            category="schema_requirement",
                            status="passed",
                            severity="error",
                            message=f"Required column '{col}' is present.",
                            affected_column=col,
                        )
                    )

            # 3. Schema drift detection
            if rules.get("disallow_schema_drift", False):
                known_contract_cols = set(required_cols).union(
                    rules.get("column_types", {}).keys(),
                    rules.get("nullable_columns", {}).keys(),
                    rules.get("unique_columns", []),
                )
                extra_cols = [c for c in actual_cols if c not in known_contract_cols]
                if extra_cols:
                    check_results.append(
                        CheckResult(
                            name="schema_drift_check",
                            category="schema_drift",
                            status="failed",
                            severity="warning",
                            message=f"Disallowed unexpected columns detected: {extra_cols}",
                            failed_count=len(extra_cols),
                            sample_failures=extra_cols[:10],
                            recommendation="Drop unexpected columns or update contract rules to include them.",
                        )
                    )

            # 4. Nullable / Non-nullable constraints
            nullable_rules = rules.get("nullable_columns", {})
            for col, allowed_null in nullable_rules.items():
                if col in actual_cols:
                    null_mask = df[col].isna()
                    null_count = int(null_mask.sum())
                    if not allowed_null and null_count > 0:
                        fail_rate = round(null_count / row_count, 4) if row_count > 0 else 1.0
                        sample_indices = df[null_mask].index[:10].tolist()
                        for v_idx in df[null_mask].index:
                            row_errors.setdefault(int(v_idx), []).append({
                                "rule": "not_null",
                                "column": col,
                                "message": f"Column '{col}' is null but marked non-nullable.",
                            })
                        check_results.append(
                            CheckResult(
                                name=f"not_null:{col}",
                                category="nullability",
                                status="failed",
                                severity="error",
                                message=f"Column '{col}' is marked non-nullable but contains {null_count} nulls.",
                                affected_column=col,
                                failed_count=null_count,
                                failure_rate=fail_rate,
                                sample_failures=[f"Row {idx}" for idx in sample_indices],
                                recommendation=f"Fill or remove null values in '{col}' using transformation.",
                            )
                        )
                    else:
                        check_results.append(
                            CheckResult(
                                name=f"nullability:{col}",
                                category="nullability",
                                status="passed",
                                severity="error",
                                message=f"Column '{col}' satisfies nullability rule (nulls: {null_count}).",
                                affected_column=col,
                            )
                        )

            # 5. Uniqueness constraints
            unique_cols = rules.get("unique_columns", [])
            for col in unique_cols:
                if col in actual_cols:
                    non_null = df[col].dropna()
                    dup_mask = df[col].duplicated(keep=False) & df[col].notna()
                    dup_count = int(non_null.duplicated().sum())
                    if dup_count > 0:
                        fail_rate = round(dup_count / len(non_null), 4) if len(non_null) > 0 else 1.0
                        dups = non_null[non_null.duplicated()].head(10).tolist()
                        for v_idx in df[dup_mask].index:
                            val = df.at[v_idx, col]
                            row_errors.setdefault(int(v_idx), []).append({
                                "rule": "uniqueness",
                                "column": col,
                                "message": f"Column '{col}' has duplicate value: {val}",
                            })
                        check_results.append(
                            CheckResult(
                                name=f"uniqueness:{col}",
                                category="uniqueness",
                                status="failed",
                                severity="error",
                                message=f"Column '{col}' has {dup_count} duplicate values.",
                                affected_column=col,
                                failed_count=dup_count,
                                failure_rate=fail_rate,
                                sample_failures=dups,
                                recommendation=f"Apply remove_duplicates transformation or deduplicate key '{col}'.",
                            )
                        )
                    else:
                        check_results.append(
                            CheckResult(
                                name=f"uniqueness:{col}",
                                category="uniqueness",
                                status="passed",
                                severity="error",
                                message=f"Column '{col}' values are unique.",
                                affected_column=col,
                            )
                        )

            # 6. Type expectations
            type_rules = rules.get("column_types", {})
            for col, expected_type in type_rules.items():
                if col in actual_cols:
                    non_null = df[col].dropna()
                    mismatches = []
                    if expected_type == "int":
                        for idx, val in non_null.items():
                            try:
                                if not float(val).is_integer():
                                    mismatches.append(val)
                                    row_errors.setdefault(int(idx), []).append({
                                        "rule": "column_type",
                                        "column": col,
                                        "message": f"Value '{val}' cannot be parsed as integer.",
                                    })
                            except (ValueError, TypeError):
                                mismatches.append(val)
                                row_errors.setdefault(int(idx), []).append({
                                    "rule": "column_type",
                                    "column": col,
                                    "message": f"Value '{val}' cannot be parsed as integer.",
                                })
                    elif expected_type == "float":
                        for idx, val in non_null.items():
                            try:
                                float(val)
                            except (ValueError, TypeError):
                                mismatches.append(val)
                                row_errors.setdefault(int(idx), []).append({
                                    "rule": "column_type",
                                    "column": col,
                                    "message": f"Value '{val}' cannot be parsed as float.",
                                })
                    elif expected_type == "datetime":
                        for idx, val in non_null.items():
                            try:
                                pd.to_datetime(val)
                            except (ValueError, TypeError):
                                mismatches.append(val)
                                row_errors.setdefault(int(idx), []).append({
                                    "rule": "column_type",
                                    "column": col,
                                    "message": f"Value '{val}' cannot be parsed as datetime.",
                                })

                    if mismatches:
                        check_results.append(
                            CheckResult(
                                name=f"type_check:{col}",
                                category="data_type",
                                status="failed",
                                severity="error",
                                message=f"Column '{col}' has values incompatible with expected type '{expected_type}'.",
                                affected_column=col,
                                failed_count=len(mismatches),
                                sample_failures=mismatches[:10],
                                recommendation=f"Cast column '{col}' to '{expected_type}' or clean invalid values.",
                            )
                        )
                    else:
                        check_results.append(
                            CheckResult(
                                name=f"type_check:{col}",
                                category="data_type",
                                status="passed",
                                severity="error",
                                message=f"Column '{col}' conforms to expected type '{expected_type}'.",
                                affected_column=col,
                            )
                        )

            # 7. Allowed values check
            allowed_rules = rules.get("allowed_values", {})
            for col, allowed_vals in allowed_rules.items():
                if col in actual_cols:
                    non_null = df[col].dropna()
                    allowed_set = set(str(v) for v in allowed_vals)
                    invalid = []
                    for idx, val in non_null.items():
                        if str(val) not in allowed_set:
                            invalid.append(val)
                            row_errors.setdefault(int(idx), []).append({
                                "rule": "allowed_values",
                                "column": col,
                                "message": f"Value '{val}' is not in permitted set {allowed_vals}.",
                            })
                    if invalid:
                        check_results.append(
                            CheckResult(
                                name=f"allowed_values:{col}",
                                category="validity",
                                status="failed",
                                severity="error",
                                message=f"Column '{col}' contains {len(invalid)} values not in allowed set.",
                                affected_column=col,
                                failed_count=len(invalid),
                                sample_failures=invalid[:10],
                                recommendation=f"Filter or normalize invalid categories in '{col}'.",
                            )
                        )
                    else:
                        check_results.append(
                            CheckResult(
                                name=f"allowed_values:{col}",
                                category="validity",
                                status="passed",
                                severity="error",
                                message=f"Column '{col}' contains only permitted values.",
                                affected_column=col,
                            )
                        )

            # 8. Numeric range check
            range_rules = rules.get("numeric_ranges", {})
            for col, range_cfg in range_rules.items():
                if col in actual_cols:
                    min_val = range_cfg.get("min")
                    max_val = range_cfg.get("max")
                    violators = []
                    for idx, val in df[col].dropna().items():
                        try:
                            num = float(val)
                            is_violation = False
                            if min_val is not None and num < min_val:
                                is_violation = True
                            if max_val is not None and num > max_val:
                                is_violation = True
                            if is_violation:
                                violators.append(num)
                                row_errors.setdefault(int(idx), []).append({
                                    "rule": "numeric_range",
                                    "column": col,
                                    "message": f"Value {num} outside expected range [{min_val}, {max_val}].",
                                })
                        except (ValueError, TypeError):
                            pass

                    if violators:
                        check_results.append(
                            CheckResult(
                                name=f"range_check:{col}",
                                category="range_constraint",
                                status="failed",
                                severity="error",
                                message=f"Column '{col}' has values outside range [{min_val}, {max_val}].",
                                affected_column=col,
                                failed_count=len(violators),
                                sample_failures=violators[:10],
                                recommendation=f"Filter rows where '{col}' is outside expected range.",
                            )
                        )
                    else:
                        check_results.append(
                            CheckResult(
                                name=f"range_check:{col}",
                                category="range_constraint",
                                status="passed",
                                severity="error",
                                message=f"Column '{col}' values fall within bounds [{min_val}, {max_val}].",
                                affected_column=col,
                            )
                        )

            # Summary counts
            passed_count = sum(1 for c in check_results if c.status == "passed")
            failed_count = sum(1 for c in check_results if c.status == "failed")
            overall_status = "passed" if failed_count == 0 else "failed"

            # Row-level quarantine and accepted/rejected partitioning
            invalid_indices = sorted(list(row_errors.keys()))
            rejected_rows_count = len(invalid_indices)
            accepted_rows_count = row_count - rejected_rows_count

            run_id = str(uuid.uuid4())
            quarantine_path = None
            clean_path = None

            if rejected_rows_count > 0:
                rejected_df = df.iloc[invalid_indices].copy()
                quarantine_path, _, _ = self.storage.save_dataframe(
                    dataset_id=version.dataset_id,
                    version_id=f"quarantine_{run_id[:8]}",
                    df=rejected_df,
                )

            if accepted_rows_count > 0:
                clean_df = df.drop(index=invalid_indices).copy()
                clean_path, _, _ = self.storage.save_dataframe(
                    dataset_id=version.dataset_id,
                    version_id=f"clean_{run_id[:8]}",
                    df=clean_df,
                )

            run = ValidationRun(
                id=run_id,
                dataset_id=version.dataset_id,
                version_id=version.id,
                contract_id=contract.id,
                status=overall_status,
                passed_count=passed_count,
                failed_count=failed_count,
                accepted_rows=accepted_rows_count,
                rejected_rows=rejected_rows_count,
                quarantine_path=quarantine_path,
                clean_path=clean_path,
                results_json={
                    "contract_name": contract.name,
                    "overall_status": overall_status,
                    "passed_count": passed_count,
                    "failed_count": failed_count,
                    "accepted_rows": accepted_rows_count,
                    "rejected_rows": rejected_rows_count,
                    "quarantine_path": quarantine_path,
                    "clean_path": clean_path,
                    "checks": [c.model_dump() for c in check_results],
                },
            )
            db.add(run)

            # Persist row-level rejection details for audit and diagnosis
            for idx in invalid_indices:
                raw_row = df.iloc[idx].to_dict()
                clean_raw = {str(k): (None if pd.isna(v) else v) for k, v in raw_row.items()}
                rejection = ValidationRejection(
                    run_id=run_id,
                    dataset_id=version.dataset_id,
                    version_id=version.id,
                    row_number=idx + 1,
                    raw_data=clean_raw,
                    failure_reasons=row_errors[idx],
                )
                db.add(rejection)

            db.commit()
            db.refresh(run)

            log_audit(
                db,
                event_type="validation.executed",
                entity_type="contract",
                entity_id=contract.id,
                outcome=overall_status,
                dataset_id=version.dataset_id,
                version_id=version.id,
                details={
                    "status": overall_status,
                    "passed_count": passed_count,
                    "failed_count": failed_count,
                    "accepted_rows": accepted_rows_count,
                    "rejected_rows": rejected_rows_count,
                },
            )

            complete_job(db, job, status="succeeded")
            return run

        except Exception as exc:
            db.rollback()
            err_cat = classify_exception(exc)
            complete_job(db, job, status="failed", error_message=str(exc), error_category=err_cat)
            log_audit(
                db,
                event_type="validation.failed",
                entity_type="contract",
                entity_id=contract.id,
                outcome="failure",
                dataset_id=version.dataset_id,
                version_id=version.id,
                details={"error": str(exc), "error_category": err_cat},
            )
            raise

    def get_rejections(
        self,
        db: Session,
        run_id: str,
        skip: int = 0,
        limit: int = 50,
    ) -> Tuple[List[ValidationRejection], int]:
        """Fetch paginated row-level rejections for a validation run."""
        stmt = select(ValidationRejection).where(ValidationRejection.run_id == run_id)
        total = db.scalar(select(func.count()).select_from(stmt.subquery())) or 0
        items = db.scalars(
            stmt.order_by(ValidationRejection.row_number.asc()).offset(skip).limit(limit)
        ).all()
        return list(items), total
